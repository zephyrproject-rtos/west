#[test]
#[serial]
fn refuses_to_overwrite_without_force() {
    let sb = Sandbox::new();
    std::fs::write(&sb.v1_local, "[manifest]\npath = zephyr\n").unwrap();
    std::fs::write(&sb.v2_local, "# existing v2 content\n").unwrap();

    let out = sb
        .west()
        .args(["config", "migrate", "--local"])
        .output()
        .unwrap();
    // Returns non-zero (FAILURE) because the only requested scope was skipped.
    assert!(!out.status.success());
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("already exists"), "stderr was: {stderr}");

    // v2 file is unchanged.
    assert_eq!(read(&sb.v2_local), "# existing v2 content\n");
}

#[test]
#[serial]
fn force_overwrites_existing() {
    let sb = Sandbox::new();
    std::fs::write(&sb.v1_local, "[manifest]\npath = zephyr\n").unwrap();
    std::fs::write(&sb.v2_local, "# stale\n").unwrap();

    sb.west()
        .args(["config", "migrate", "--local", "--force"])
        .assert()
        .success();

    let toml = read(&sb.v2_local);
    assert!(!toml.contains("# stale"));
    assert!(toml.contains("path = \"zephyr\""));
}

#[test]
#[serial]
fn dry_run_writes_nothing_prints_body() {
    let sb = Sandbox::new();
    std::fs::write(&sb.v1_local, "[manifest]\npath = zephyr\n").unwrap();
    assert!(!sb.v2_local.exists());

    let out = sb
        .west()
        .args(["config", "migrate", "--local", "--dry-run"])
        .output()
        .unwrap();
    assert!(out.status.success());
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(stdout.contains("would write to"));
    assert!(stdout.contains("path = \"zephyr\""));
    assert!(!sb.v2_local.exists(), "v2 file must not exist after --dry-run");
}

