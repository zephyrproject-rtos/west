//! Integration tests for `west config migrate`.
//!
//! Each test writes a v1 INI file in a tempdir and runs the binary
//! against it. `--local` paths off the workspace; the `--from PATH
//! --file PATH` pairing covers the non-local scopes without touching
//! `/etc/westconfig` / `~/.westconfig` for real.

use std::path::Path;

use assert_cmd::Command;
use serial_test::serial;
use tempfile::TempDir;

const BIN: &str = "west";

struct Sandbox {
    _tmp: TempDir,
    workspace: std::path::PathBuf,
    v1_local: std::path::PathBuf,
    v2_local: std::path::PathBuf,
}

impl Sandbox {
    fn new() -> Self {
        let tmp = TempDir::new().unwrap();
        let workspace = tmp.path().join("ws");
        std::fs::create_dir_all(workspace.join(".west")).unwrap();
        // West marker file so topdir() resolves to `workspace`.
        std::fs::write(workspace.join(".west").join("config.toml.placeholder"), "").ok();
        let v1_local = workspace.join(".west").join("config");
        let v2_local = workspace.join(".west").join("config.toml");
        Sandbox {
            _tmp: tmp,
            workspace,
            v1_local,
            v2_local,
        }
    }

    fn west(&self) -> Command {
        let mut c = Command::cargo_bin(BIN).unwrap();
        // `--local` finds the v1 source via topdir from cwd and the v2
        // target via the same topdir; `--from PATH --file PATH` tests
        // sidestep both. HOME is pinned so the v1 global resolver
        // doesn't see the developer's real `~/.westconfig`. XDG is
        // unset for the same reason.
        //
        // `WEST_CONFIG_{LOCAL,GLOBAL,SYSTEM}` are intentionally unset
        // here. The v1 resolver doesn't consult them (we dropped that
        // after seeing it conflicted with v2's meaning for the same
        // env vars). The no-scope mode test is the only spot that
        // could pick up `/etc/westconfig` etc. on a dirty dev box;
        // that's an accepted, narrow exposure.
        c.current_dir(&self.workspace)
            .env_remove("WEST_CONFIG_LOCAL")
            .env_remove("WEST_CONFIG_GLOBAL")
            .env_remove("WEST_CONFIG_SYSTEM")
            .env("HOME", self._tmp.path())
            .env_remove("XDG_CONFIG_HOME");
        c
    }
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_default()
}

#[test]
#[serial]
fn round_trip_basic_keys() {
    let sb = Sandbox::new();
    std::fs::write(
        &sb.v1_local,
        "[manifest]\npath = zephyr\nfile = west.yml\n\n[update]\njobs = 8\n",
    )
    .unwrap();

    sb.west()
        .args(["config", "migrate", "--local"])
        .assert()
        .success();

    let toml = read(&sb.v2_local);
    assert!(toml.starts_with("# Generated by `west config migrate` (west "));
    assert!(toml.contains("path = \"zephyr\""));
    assert!(toml.contains("file = \"west.yml\""));
    // Known-int key coerces to a bare integer, not a string.
    assert!(toml.contains("jobs = 8"));
    assert!(!toml.contains("jobs = \"8\""));
    // v1 file untouched.
    assert!(sb.v1_local.exists());
}

