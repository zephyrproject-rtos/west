#[test]
#[serial]
fn from_path_with_file_target() {
    // `--from PATH --file PATH` decouples source from target; used by
    // tests + users with non-conventional layouts.
    let tmp = TempDir::new().unwrap();
    let v1 = tmp.path().join("oldconfig");
    let v2 = tmp.path().join("newconfig.toml");
    std::fs::write(&v1, "[manifest]\npath = zephyr\n").unwrap();

    let mut c = Command::cargo_bin(BIN).unwrap();
    c.args([
        "config",
        "migrate",
        "--from",
        v1.to_str().unwrap(),
        "--file",
        v2.to_str().unwrap(),
    ])
    // Keep the test hermetic — no ambient layer files.
    .env_remove("WEST_CONFIG_LOCAL")
    .env_remove("WEST_CONFIG_GLOBAL")
    .env_remove("WEST_CONFIG_SYSTEM")
    .env("HOME", tmp.path())
    .env_remove("XDG_CONFIG_HOME");
    c.assert().success();

    let toml = read(&v2);
    assert!(toml.contains("path = \"zephyr\""));
}

#[cfg(target_os = "linux")]
#[test]
#[serial]
fn linux_global_falls_back_to_dotwestconfig_when_xdg_path_absent() {
    // Linux-only: when XDG_CONFIG_HOME is set but no file exists at
    // `$XDG_CONFIG_HOME/west/config`, the v1 resolver should still find
    // `~/.westconfig` if the user has one there. (v1.5.0 didn't fall
    // back; we deviate intentionally — see comment in v1_global_default.)
    let tmp = TempDir::new().unwrap();
    // XDG_CONFIG_HOME is set but the file at $XDG_CONFIG_HOME/west/config
    // doesn't exist — only the directory needs to (so v2 can write its
    // .toml output into it without create_dir_all racing the test).
    let xdg = tmp.path().join("xdg-home");
    std::fs::create_dir_all(xdg.join("west")).unwrap();
    let home = tmp.path().join("home");
    std::fs::create_dir(&home).unwrap();
    let westconfig = home.join(".westconfig");
    std::fs::write(&westconfig, "[manifest]\npath = via-fallback\n").unwrap();

    let v2_global = xdg.join("west").join("config.toml");

    let mut c = Command::cargo_bin(BIN).unwrap();
    c.args(["config", "migrate", "--global"])
        // XDG sets BOTH the would-be v1 path ($XDG/west/config — absent)
        // AND v2's write target ($XDG/west/config.toml — gets created by
        // the migration). Leaving WEST_CONFIG_GLOBAL unset is what makes
        // the v1 resolver actually exercise v1_global_default, the code
        // under test.
        .env("XDG_CONFIG_HOME", &xdg)
        .env("HOME", &home)
        .env_remove("WEST_CONFIG_LOCAL")
        .env_remove("WEST_CONFIG_GLOBAL")
        .env_remove("WEST_CONFIG_SYSTEM");
    c.assert().success();

    let body = read(&v2_global);
    assert!(
        body.contains("path = \"via-fallback\""),
        "expected migration to read ~/.westconfig via fallback, got: {body}"
    );
}

